package org.nasedka.app;

import java.util.Arrays;
import java.util.Collections;
import java.util.List;

/**
 * Preparation steps grounded in the user's 2021 "Несушка" operating manual.
 * For unknown incubators the list is intentionally generic, without Nesushka-specific rules.
 * Each checkbox is a user self-report; the app cannot inspect physical equipment.
 */
public final class IncubationPreparation {
    private IncubationPreparation() {}

    public static final String SOURCE = "Руководство инкубатора «Несушка» (2021)";

    public static final class Step {
        public final String title;
        public final String explanation;
        public final String source;

        public Step(String title, String explanation, String source) {
            this.title = title;
            this.explanation = explanation;
            this.source = source;
        }
    }

    private static final List<Step> NESUSHKA = Collections.unmodifiableList(Arrays.asList(
            new Step("Выбрано безопасное место",
                    "Свободная вентиляция; нет прямого солнца и сквозняка; инкубатор не стоит на полу. В руководстве указан желательный диапазон помещения 20–25 °C.",
                    "п. 1.2, стр. 1"),
            new Step("Корпус, сетевой кабель и комплектация проверены",
                    "Убедитесь в целостности корпуса и изоляции провода. При повреждении кабеля не используйте устройство.",
                    "пп. 4.2, 6.1, стр. 2–3"),
            new Step("Решётки и датчик установлены по инструкции",
                    "Решётки размещены правильно; датчик находится в районе яиц и не касается их. Сборку выполняйте при отключённом питании.",
                    "пп. 6.2–6.5, стр. 3–4"),
            new Step("Работоспособность оборудования проверена",
                    "Проверены включение и показания терморегулятора; при наличии автоматического переворота — его работа согласно руководству.",
                    "пп. 6.6–6.7, стр. 4"),
            new Step("Подготовлена вода по таблице своей модели",
                    "Для углублений руководство указывает тёплую воду около 35 °C. Количество заполненных ячеек зависит от влажности и вместимости модели.",
                    "пп. 7.1–7.3, стр. 4–5"),
            new Step("Яйца отобраны и осмотрены",
                    "Руководство рекомендует свежие, чистые немытые, бездефектные яйца средней величины; при возможности проверьте овоскопом.",
                    "п. 7.6, стр. 6"),
            new Step("Инкубатор прогрет, температура проверена",
                    "Дождитесь стабилизации фактической температуры до закладки. Заводская настройка 38,0 °C не является универсальной нормой для всех видов птицы.",
                    "пп. 7.4–7.7, стр. 5–6"),
            new Step("Правила безопасности прочитаны",
                    "Перед открытием крышки отключайте инкубатор от сети 220 В. Не разбирайте и не переделывайте электрические части самостоятельно.",
                    "пп. 4.1, 4.5–4.6, стр. 2")
    ));

    private static final List<Step> OTHER = Collections.unmodifiableList(Arrays.asList(
            new Step("Изучена инструкция именно этой модели",
                    "Сверьте устройство, способ переворота и требуемые условия с официальным руководством своего инкубатора.",
                    "Универсальный проверочный список пользователя"),
            new Step("Проверены безопасность и исправность",
                    "Осмотрите корпус и кабель, выберите безопасное проветриваемое место по инструкции производителя.",
                    "Универсальный проверочный список пользователя"),
            new Step("Яйца отобраны и осмотрены",
                    "Проверьте состояние скорлупы и пригодность яиц для выбранного вида птицы; уточните требования к хранению.",
                    "Универсальный проверочный список пользователя"),
            new Step("Подготовлены вода и режимы, если требуются",
                    "Следуйте таблицам и правилам своей модели. Нормы воды и работа переворота «Несушки» здесь НЕ применяются.",
                    "Универсальный проверочный список пользователя"),
            new Step("Проверены фактические условия до закладки",
                    "Убедитесь по отдельному измерителю или показаниям оборудования, что режим соответствует вашему руководству.",
                    "Универсальный проверочный список пользователя")
    ));

    public static List<Step> steps(boolean nesushka) {
        return nesushka ? NESUSHKA : OTHER;
    }

    public static String journalNote(boolean nesushka, String model) {
        String label = nesushka ? "«Несушка» БИ-1/БИ-2, вместимость " + model
                                : "ручная модель «" + model + "»";
        String source = nesushka ? SOURCE + ", пункты 1.2, 4, 6, 7"
                                 : "индивидуальная инструкция модели не проверена приложением";
        return "ПОДГОТОВКА ПЕРЕД ЗАКЛАДКОЙ. Пользователь отметил все пункты проверочного списка. "
                + "Модель: " + label + ". Основание: " + source + ". "
                + "Это пользовательские отметки, а не автоматическая проверка условий.";
    }
}
