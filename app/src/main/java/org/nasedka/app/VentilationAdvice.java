package org.nasedka.app;

/**
 * Ventilation (ongoing air exchange) and periodic egg cooling are distinct.
 * Source: original user-provided Nesushka operating instructions (2021), §§1.2,
 * 4.1, 8.10, recommendations p.9. The manual provides NO fixed daily cooling
 * duration/frequency, so this class must not invent one.
 */
public final class VentilationAdvice {
    private VentilationAdvice() {}

    public static String exchange(Batch batch) {
        if (!batch.isNesushka()) {
            return "Воздухообмен необходим на протяжении инкубации. "
                    + "Проверьте, какие вентиляционные отверстия предусмотрены "
                    + "именно вашей моделью, и следуйте её руководству. "
                    + "Правила «Несушки» автоматически не применяются.";
        }
        return "В штатном режиме обеспечьте приток свежего воздуха к "
                + "вентиляционным отверстиям инкубатора; не ставьте его на сквозняке "
                + "и под прямыми солнечными лучами. При ежедневных проверках "
                + "убеждайтесь, что воздухообмен не нарушен. "
                + "При аварийном отключении питания действуют отдельные указания инструкции.";
    }

    public static String cooling(Batch batch) {
        if (!batch.isNesushka()) {
            return "Периодическое проветривание/охлаждение яиц — отдельная процедура. "
                    + "Без подтверждённой инструкции для вашей модели и вида птицы "
                    + "приложение не задаёт время открытия крышки или охлаждения.";
        }
        String text = "Руководство «Несушки» (2021) НЕ устанавливает, "
                + "сколько раз в сутки и сколько минут специально охлаждать яйца. "
                + "Не путайте такой режим с обычной вентиляцией через отверстия. "
                + "При длительном открытии крышки температура падает; "
                + "перед её открытием отключайте питание 220 В. "
                + "Уточните режим охлаждения для вашего вида птицы и оборудования.";
        if (Batch.DUCK.equals(batch.species) || Batch.GOOSE.equals(batch.species)) {
            text += " Для утиных и гусиных яиц в инструкции отдельно описано "
                    + "орошение во второй половине инкубации; это не то же самое, "
                    + "что специальное охлаждение.";
        }
        return text;
    }

    public static String source(Batch batch) {
        return batch.isNesushka()
                ? "«Несушка», 2021: воздухообмен — п. 1.2, стр. 1 и п. 8.10, стр. 8; "
                    + "безопасность — п. 4.1, стр. 2; открытие крышки — стр. 9; "
                    + "орошение уток и гусей — стр. 5."
                : "Основание — общая памятка. Проверенный режим вашей модели не внесён.";
    }
}
